def save_cycle_comparison_plots(
    *,
    baseline_phase,
    optimized_phase=None,
    result=None,
    seed_config=None,
    optimized_config=None,
    out_dir=".",
    tag="cycle",
    show=False,
    dpi=150,
):
    """Build and save the seed-vs-optimized comparison figures.

    The optimized cycle comes straight from ``result`` (a
    ``SimulationResult``) -- the NLP's own per-node trajectory, no
    re-simulation involved. Passing ``optimized_phase`` (a re-simulated
    phase) overrides that source. Figures are written to ``out_dir`` and,
    unless ``show``, closed after saving (with ``show`` they stay open for
    the caller's ``plt.show()``). Returns the list of written paths.
    """
    import matplotlib.pyplot as plt

    seed = series_from_phase(baseline_phase) if baseline_phase is not None else None
    opt = None
    if optimized_phase is not None:
        opt = series_from_phase(optimized_phase)
        opt_source = "re-simulated optimized cycle"
    if not opt and result is not None:
        opt = series_from_optimizer_result(
            result, (optimized_config or {}).get("path_parameters")
        )
        opt_source = "NLP's own per-node solution"
    if opt:
        print(f"Comparison plots: optimized series from the {opt_source}.")
    else:
        print("Comparison plots: no optimized series available; plotting seed only.")

    seed_m = cycle_metrics(seed) if seed else {}
    opt_m = cycle_metrics(opt) if opt else {}
    rows = comparison_rows(seed_m, opt_m)
    print_comparison(rows)

    seed_path = (seed_config or {}).get("path_parameters")
    opt_path = (optimized_config or {}).get("path_parameters")
    figures = (
        (
            "trajectory",
            lambda: plot_trajectory_comparison(
                seed, opt, seed_path=seed_path, opt_path=opt_path, title=tag
            ),
        ),
        ("timeseries", lambda: plot_timeseries_comparison(seed, opt, title=tag)),
        (
            "power",
            lambda: plot_power_summary(
                seed,
                opt,
                seed_m,
                opt_m,
                rows,
                seed_config=seed_config,
                opt_config=optimized_config,
                title=tag,
            ),
        ),
    )

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    saved = []
    for name, builder in figures:
        try:
            fig = builder()
        except Exception as exc:
            print(f"(comparison figure '{name}' unavailable: {exc})")
            continue
        path = out_dir / f"full_cycle_compare_{tag}_{name}.png"
        fig.savefig(path, dpi=dpi, bbox_inches="tight")
        saved.append(path)
        if not show:
            plt.close(fig)
    if saved:
        print("Comparison plots saved to:")
