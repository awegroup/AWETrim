"""Seed-vs-optimized comparison plots for the full pumping-cycle optimization.

Companion to ``run_full_cycle_opti.py``: after a successful staged solve it
renders a detailed comparison between the *initial guess* (the seed cycle
generated by ``fit_periodic_cycle_config.py`` and forward-simulated as the NLP
warm start) and the *optimized* cycle. Three figures are saved next to the
optimized YAML/CSV in the results directory:

  ``..._trajectory.png``   3D flight path and the azimuth-elevation wind
                           window (seed / optimized spline paths + the flown
                           node trajectories);
  ``..._timeseries.png``   states and controls over the cycle phase s --
                           radius, reel speed, tension, power, steering,
                           depower, angle of attack -- with the optimized
                           reel-in window shaded;
  ``..._power.png``        instantaneous + cycle-average power, cumulative
                           energy over the cycle, the winch operating plane
                           T(v_r) against the force law and clamps, and a
                           seed -> optimized metrics table.

The optimized series is read straight from the optimizer's own per-node
trajectory (``SimulationResult.optimized_trajectory``) -- no re-simulation is
needed: time is reconstructed from ``dt = ds / s_dot`` and the path angles
from the optimized spline at the solved (r, s) nodes. A re-simulated phase
can optionally be passed as ``optimized_phase`` to plot the re-flown cycle
instead.

All entry points are best-effort: a broken panel or missing variable costs
that trace only, never the run that produced the result.
"""

from pathlib import Path

import numpy as np

from awetrim.kinematics.parametrized_patterns import PeriodicBSpline

SEED_STYLE = {"color": "0.45", "linestyle": "--", "linewidth": 1.4}
OPT_STYLE = {"color": "tab:blue", "linestyle": "-", "linewidth": 1.7}
SEED_LABEL = "initial guess"
OPT_LABEL = "optimized"
REELIN_SHADE = {"color": "tab:orange", "alpha": 0.12, "zorder": 0}

_SERIES_KEYS = (
    "t",
    "s",
    "s_dot",
    "distance_radial",
    "speed_radial",
    "tension_tether_ground",
    "input_steering",
    "input_depower",
    "angle_azimuth",
    "angle_elevation",
    "speed_tangential",
    "mechanical_power",
    "angle_of_attack",
)


# ---------------------------------------------------------------------------
# Series extraction
# ---------------------------------------------------------------------------
def _ensure_power(series):
    if "mechanical_power" not in series and {
        "tension_tether_ground",
        "speed_radial",
    } <= series.keys():
        n = min(len(series["tension_tether_ground"]), len(series["speed_radial"]))
        series["mechanical_power"] = (
            series["tension_tether_ground"][:n] * series["speed_radial"][:n]
        )


def series_from_phase(phase):
    """Plain dict of numpy arrays from a simulated ``PhaseParameterized``.

    Variables the model does not expose (e.g. angle_of_attack on some
    configurations) are skipped; mechanical power falls back to T * v_r when
    not recorded.
    """
    out = {}
    for key in _SERIES_KEYS:
        try:
            values = np.asarray(phase.return_variable(key), dtype=float).ravel()
        except Exception:
            continue
        if values.size:
            out[key] = values
    _ensure_power(out)
    return out


def series_from_optimizer_result(result, path_parameters):
    """Series dict straight from the NLP solution (re-simulation fallback).

    ``optimized_trajectory`` carries the per-node decision values only, so
    time is integrated from ``dt = ds / s_dot`` and the path angles are
    evaluated from the optimized spline at the solved (r, s) nodes. Returns
    None when the result holds no trajectory.
    """
    traj = getattr(result, "optimized_trajectory", None) or {}
    if not traj:
        return None
    out = {k: np.asarray(v, dtype=float).ravel() for k, v in traj.items()}
    n = min(len(v) for v in out.values())
    out = {k: v[:n] for k, v in out.items()}
    _ensure_power(out)
    if "t" not in out and {"s", "s_dot"} <= out.keys():
        ds = np.diff(out["s"], prepend=out["s"][0])
        out["t"] = np.cumsum(ds / np.maximum(out["s_dot"], 1e-9))
    if (
        path_parameters is not None
        and "angle_azimuth" not in out
        and {"s", "distance_radial"} <= out.keys()
    ):
        try:
            pattern = _pattern(path_parameters)
            r, s = out["distance_radial"], out["s"]
            out["angle_azimuth"] = np.array(
                [float(pattern.azimuth(r[j], s[j])) for j in range(n)]
            )
            out["angle_elevation"] = np.array(
                [float(pattern.elevation(r[j], s[j])) for j in range(n)]
            )
        except Exception:
            pass
    return out


def _pattern(path_parameters):
    M = int(path_parameters["M"])
    return PeriodicBSpline(
        M=M,
        C_phi=np.asarray(path_parameters["C_phi"], dtype=float).reshape((M, 1)),
        C_beta=np.asarray(path_parameters["C_beta"], dtype=float).reshape((M, 1)),
        s_init=float(path_parameters.get("s_init", 0.0)),
        s_final=float(path_parameters.get("s_final", 1.0)),
        downloops=bool(path_parameters.get("downloops", True)),
    )


def _sample_spline(path_parameters, n_samples=600):
    """(azimuth, elevation) in degrees over one period of the config's spline."""
    pattern = _pattern(path_parameters)
    r0 = float(path_parameters["r0"])
    s = np.linspace(0.0, 1.0, n_samples, endpoint=True)
    phi = np.degrees([float(pattern.azimuth(r0, si)) for si in s])
    beta = np.degrees([float(pattern.elevation(r0, si)) for si in s])
    return phi, beta


# ---------------------------------------------------------------------------
# Metrics
# ---------------------------------------------------------------------------
def cycle_metrics(series):
    """Scalar cycle metrics (energy, power, closure, ...) from a series dict."""
    m = {}
    t = series.get("t")
    tension = series.get("tension_tether_ground")
    vr = series.get("speed_radial")
    if t is not None and tension is not None and vr is not None and len(t) > 1:
        n = min(len(t), len(tension), len(vr))
        t_n, tension_n, vr_n = t[:n], tension[:n], vr[:n]
        dt = np.diff(t_n, prepend=t_n[0])
        duration = float(t_n[-1] - t_n[0])
        m["energy"] = float(np.sum(tension_n * vr_n * dt))
        m["duration"] = duration
        m["avg_power"] = m["energy"] / max(duration, 1e-9)
        m["reelout_time_fraction"] = float(
            np.sum(dt[vr_n > 0.0]) / max(duration, 1e-9)
        )
        m["tension_mean"] = float(np.mean(tension_n))
        m["tension_max"] = float(np.max(tension_n))
    r = series.get("distance_radial")
    if r is not None and len(r) > 1:
        m["closure"] = float(r[-1] - r[0])
        m["r_min"], m["r_max"] = float(np.min(r)), float(np.max(r))
    u_s = series.get("input_steering")
    if u_s is not None and len(u_s):
        m["steer_absmax"] = float(np.max(np.abs(u_s)))
    dep = series.get("input_depower")
    if dep is not None and len(dep):
        m["depower_min"] = float(np.min(dep))
        m["depower_max"] = float(np.max(dep))
    return m


def _fmt(value, spec, unit=""):
    return "n/a" if value is None else f"{value:{spec}}{unit}"


def comparison_rows(seed_m, opt_m):
    """(metric, seed, optimized, change) rows for the console table and figure."""
    rows = []

    def add(name, key, spec, unit="", scale=1.0, pct=False):
        a, b = seed_m.get(key), opt_m.get(key)
        delta = ""
        if pct and a not in (None, 0) and b is not None:
            delta = f"{(b - a) / abs(a) * 100.0:+.1f}%"
        rows.append(
            (
                name,
                _fmt(None if a is None else a * scale, spec, unit),
                _fmt(None if b is None else b * scale, spec, unit),
                delta,
            )
        )

    def add_range(name, lo_key, hi_key, spec, unit=""):
        def _rng(m):
            lo, hi = m.get(lo_key), m.get(hi_key)
            if lo is None or hi is None:
                return "n/a"
            return f"{lo:{spec}}..{hi:{spec}}{unit}"

        rows.append((name, _rng(seed_m), _rng(opt_m), ""))

    add("average power", "avg_power", ".2f", " kW", scale=1e-3, pct=True)
    add("energy / cycle", "energy", ".2f", " MJ", scale=1e-6, pct=True)
    add("cycle duration", "duration", ".1f", " s")
    add("reel-out time fraction", "reelout_time_fraction", ".2f")
    add("closure r_end - r0", "closure", "+.2f", " m")
    add_range("radius range", "r_min", "r_max", ".1f", " m")
    add("tension mean", "tension_mean", ".2f", " kN", scale=1e-3)
    add("tension max", "tension_max", ".2f", " kN", scale=1e-3)
    add("max |steering|", "steer_absmax", ".2f")
    add_range("depower range", "depower_min", "depower_max", ".2f", " m")
    return rows


def print_comparison(rows):
    """Aligned seed -> optimized metrics table on the console."""
    header = f"{'metric':<24}{'seed':>16}{'optimized':>16}{'change':>10}"
    print("\n--- Cycle comparison (seed -> optimized) ---")
    print(header)
    print("-" * len(header))
    for name, a, b, d in rows:
        print(f"{name:<24}{a:>16}{b:>16}{d:>10}")


# ---------------------------------------------------------------------------
# Figure helpers
# ---------------------------------------------------------------------------
def _iter_series(seed, opt):
    if seed:
        yield seed, SEED_STYLE, SEED_LABEL
    if opt:
        yield opt, OPT_STYLE, OPT_LABEL


def _mask_ranges(x, mask):
    """Contiguous x-ranges where ``mask`` is True, as (lo, hi) tuples."""
    idx = np.flatnonzero(mask)
    if idx.size == 0:
        return []
    ranges = []
    start = prev = idx[0]
    for j in idx[1:]:
        if j == prev + 1:
            prev = j
            continue
        ranges.append((float(x[start]), float(x[prev])))
        start = prev = j
    ranges.append((float(x[start]), float(x[prev])))
    return ranges


def _reelin_ranges(series):
    """s-ranges where the cycle reels in (v_r < 0); used for shading."""
    if not series or not {"s", "speed_radial"} <= series.keys():
        return []
    n = min(len(series["s"]), len(series["speed_radial"]))
    return _mask_ranges(series["s"][:n], series["speed_radial"][:n] < 0.0)


def _shade(ax, ranges):
    for lo, hi in ranges:
        ax.axvspan(lo, hi, **REELIN_SHADE)


def _equal_aspect_3d(ax):
    lims = np.array([ax.get_xlim3d(), ax.get_ylim3d(), ax.get_zlim3d()])
    spans = lims[:, 1] - lims[:, 0]
    ax.set_box_aspect(np.maximum(spans, 1e-9))


