def plot_trajectory_comparison(seed, opt, seed_path=None, opt_path=None, title=None):
    """3D flight path (left) and azimuth-elevation wind window (right)."""
    import matplotlib.pyplot as plt

    fig = plt.figure(figsize=(13.5, 6))
    ax3d = fig.add_subplot(1, 2, 1, projection="3d")
    ax_win = fig.add_subplot(1, 2, 2)

    for series, style, label in _iter_series(seed, opt):
        if not {"angle_azimuth", "angle_elevation", "distance_radial"} <= series.keys():
            continue
        phi, beta, r = (
            series["angle_azimuth"],
            series["angle_elevation"],
            series["distance_radial"],
        )
        n = min(len(phi), len(beta), len(r))
        phi, beta, r = phi[:n], beta[:n], r[:n]
        x = r * np.cos(beta) * np.cos(phi)
        y = r * np.cos(beta) * np.sin(phi)
        z = r * np.sin(beta)
        ax3d.plot(x, y, z, label=label, **style)
        ax3d.scatter(x[:1], y[:1], z[:1], color=style["color"], s=25)
        ax_win.plot(
            np.degrees(phi),
            np.degrees(beta),
            ".",
            color=style["color"],
            ms=3,
            alpha=0.5,
            zorder=3,
        )
    ax3d.scatter([0], [0], [0], marker="s", color="tab:brown", label="ground station")
    ax3d.set_xlabel("x (m)")
    ax3d.set_ylabel("y (m)")
    ax3d.set_zlabel("z (m)")
    ax3d.legend(loc="upper left", fontsize=9)
    ax3d.set_title("flight path (dots mark the cycle start)")
    _equal_aspect_3d(ax3d)

    # Prescribed spline paths under the simulated dots, sampled fine.
    for path, style, label in (
        (seed_path, SEED_STYLE, f"{SEED_LABEL} spline"),
        (opt_path, OPT_STYLE, f"{OPT_LABEL} spline"),
    ):
        if path is None:
            continue
        try:
            phi_deg, beta_deg = _sample_spline(path)
        except Exception:
            continue
        ax_win.plot(phi_deg, beta_deg, label=label, zorder=2, **style)
    ax_win.set_xlabel(r"azimuth $\phi$ (deg)")
    ax_win.set_ylabel(r"elevation $\beta$ (deg)")
    ax_win.grid(True, alpha=0.4)
    ax_win.legend(loc="best", fontsize=9)
    ax_win.set_title("wind window: spline paths + trimmed nodes")

    if title:
        fig.suptitle(title)
    fig.tight_layout()
    return fig


def plot_timeseries_comparison(seed, opt, title=None):
    """Stacked state/control panels over the cycle phase s, seed vs optimized."""
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch

    panels = [
        ("distance_radial", "$r$ (m)", 1.0, False),
        ("speed_radial", "$v_r$ (m/s)", 1.0, False),
        ("tension_tether_ground", "$F_t$ (kN)", 1e-3, False),
        ("mechanical_power", "$P$ (kW)", 1e-3, False),
        ("input_steering", "$u_s$ (-)", 1.0, False),
        ("input_depower", "$l_{dp}$ (m)", 1.0, False),
        ("angle_of_attack", r"$\alpha$ (deg)", 1.0, True),
    ]
    panels = [
        p for p in panels if (seed and p[0] in seed) or (opt and p[0] in opt)
    ]
    if not panels:
        raise ValueError("no plottable variables in either series")

    fig, axes = plt.subplots(
        len(panels),
        1,
        sharex=True,
        figsize=(10, 1.7 * len(panels) + 0.8),
    )
    axes = np.atleast_1d(axes)

    reelin = _reelin_ranges(opt) or _reelin_ranges(seed)
    for ax, (key, ylabel, scale, to_deg) in zip(axes, panels):
        for series, style, label in _iter_series(seed, opt):
            if key not in series or "s" not in series:
                continue
            n = min(len(series["s"]), len(series[key]))
            y = series[key][:n]
            y = np.degrees(y) if to_deg else y * scale
            ax.plot(series["s"][:n], y, label=label, **style)
        _shade(ax, reelin)
        ax.set_ylabel(ylabel)
        ax.grid(True, alpha=0.4)

    handles, _ = axes[0].get_legend_handles_labels()
    if reelin:
        handles.append(
            Patch(
                color=REELIN_SHADE["color"],
                alpha=2 * REELIN_SHADE["alpha"],
                label="reel-in ($v_r < 0$)",
            )
        )
    axes[0].legend(handles=handles, loc="upper right", ncol=3, fontsize=9)
    axes[-1].set_xlabel("cycle phase $s$ (-)")
    if title:
        fig.suptitle(title)
    fig.tight_layout()
    return fig


def plot_power_summary(
    seed, opt, seed_m, opt_m, rows, seed_config=None, opt_config=None, title=None
):
    """Power, cumulative energy, winch operating plane and the metrics table."""
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(2, 2, figsize=(13, 8.5))
    ax_p, ax_e, ax_w, ax_t = axes.ravel()

    # Instantaneous power vs s, with cycle-average lines.
    reelin = _reelin_ranges(opt) or _reelin_ranges(seed)
    for (series, style, label), metrics in zip(
        _iter_series(seed, opt), (m for m in (seed_m, opt_m) if m is not None)
    ):
        if {"s", "mechanical_power"} <= series.keys():
            n = min(len(series["s"]), len(series["mechanical_power"]))
            ax_p.plot(
                series["s"][:n],
                series["mechanical_power"][:n] / 1e3,
                label=label,
                **style,
            )
        if metrics.get("avg_power") is not None:
            ax_p.axhline(
                metrics["avg_power"] / 1e3,
                color=style["color"],
                linestyle=":",
                linewidth=1.2,
                label=f"{label} avg ({metrics['avg_power'] / 1e3:.1f} kW)",
            )
    ax_p.axhline(0.0, color="k", linewidth=0.6)
    _shade(ax_p, reelin)
    ax_p.set_xlabel("cycle phase $s$ (-)")
    ax_p.set_ylabel("$P$ (kW)")
    ax_p.grid(True, alpha=0.4)
    ax_p.legend(loc="best", fontsize=8)
    ax_p.set_title("instantaneous and cycle-average power")

    # Cumulative energy over the cycle (each series on its own clock).
    for series, style, label in _iter_series(seed, opt):
        if not {"t", "tension_tether_ground", "speed_radial"} <= series.keys():
            continue
        n = min(
            len(series["t"]),
            len(series["tension_tether_ground"]),
            len(series["speed_radial"]),
        )
        t = series["t"][:n]
        dt = np.diff(t, prepend=t[0])
        energy = np.cumsum(
            series["tension_tether_ground"][:n] * series["speed_radial"][:n] * dt
        )
        ax_e.plot(t - t[0], energy / 1e6, label=label, **style)
    ax_e.axhline(0.0, color="k", linewidth=0.6)
    ax_e.set_xlabel("$t$ (s)")
    ax_e.set_ylabel("cumulative energy (MJ)")
    ax_e.grid(True, alpha=0.4)
    ax_e.legend(loc="best", fontsize=9)
    ax_e.set_title("energy harvested over the cycle")

    # Winch operating plane: every trimmed node in (v_r, F_t), against the
    # depower-shifted force law (drawn at the depower extremes) and the clamps.
    for series, style, label in _iter_series(seed, opt):
        if not {"speed_radial", "tension_tether_ground"} <= series.keys():
            continue
        n = min(len(series["speed_radial"]), len(series["tension_tether_ground"]))
        ax_w.scatter(
            series["speed_radial"][:n],
            series["tension_tether_ground"][:n] / 1e3,
            s=10,
            alpha=0.55,
            color=style["color"],
            label=label,
        )
    radial = (opt_config or seed_config or {}).get("radial_parameters", {})
    try:
        slope = float(radial["slope_winch_ro"])
        offset0 = float(radial["offset_winch_ro"])
        gain = float(radial["winch_offset_depower_gain"])
        ref = float(radial["winch_depower_ref"])
        tf_min = float(radial["min_tether_force"])
        tf_max = float(radial["max_tether_force"])
        dep_src = (opt or seed or {}).get("input_depower")
        dep_lo = float(np.min(dep_src)) if dep_src is not None else ref
        dep_hi = float(np.max(dep_src)) if dep_src is not None else ref
        vr_lo, vr_hi = ax_w.get_xlim()
        vr_line = np.linspace(vr_lo, vr_hi, 200)
        for l_dp, ls in ((dep_lo, "-"), (dep_hi, "--")):
            offset = offset0 + gain * (l_dp - ref)
            t_line = np.clip(slope * (vr_line - offset), tf_min, tf_max)
            ax_w.plot(
                vr_line,
                t_line / 1e3,
                color="tab:red",
                linestyle=ls,
                linewidth=1.1,
                label=f"winch law @ $l_{{dp}}$={l_dp:.2f} m",
            )
        for clamp in (tf_min, tf_max):
            ax_w.axhline(clamp / 1e3, color="0.7", linewidth=0.8, zorder=0)
    except (KeyError, TypeError, ValueError):
        pass  # non-force-law configs: the operating points alone still inform
    ax_w.set_xlabel("$v_r$ (m/s)")
    ax_w.set_ylabel("$F_t$ (kN)")
    ax_w.grid(True, alpha=0.4)
    ax_w.legend(loc="best", fontsize=8)
    ax_w.set_title("winch operating plane")

    # Metrics table.
    ax_t.axis("off")
    header = f"{'metric':<24}{'seed':>16}{'optimized':>16}{'change':>9}"
    lines = [header, "-" * len(header)]
    lines += [f"{name:<24}{a:>16}{b:>16}{d:>9}" for name, a, b, d in rows]
    ax_t.text(
        0.0,
        0.95,
        "\n".join(lines),
        family="monospace",
        fontsize=9,
        va="top",
        transform=ax_t.transAxes,
    )
    ax_t.set_title("cycle metrics")

    if title:
        fig.suptitle(title)
    fig.tight_layout()
    return fig


